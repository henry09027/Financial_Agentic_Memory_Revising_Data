#!/usr/bin/env bash
# One-time setup for a fresh session (run_pipeline.sh calls this automatically if the venv is missing).
# Everything large lives under WORK (default: the folder containing pit_pipeline/):
#   WORK/envs/pit              virtualenv: vLLM + torch (~10 GB)
#   WORK/.cache/huggingface    model downloads (~33 GB for the three models)
#   WORK/.cache/{pip,vllm,triton,inductor}
# TMPDIR stays /tmp: vLLM puts IPC sockets there and socket paths must be < 108 characters.
# No conda env (conda's ToS prompt blocks `conda create`), nothing in ~/.local, nothing from conda base's site-packages
# (conda's pyzmq needs a newer libstdc++ than the system has).
#
#   bash setup_env.sh                       # pinned, tested stack (vLLM 0.32.0 + CUDA 12.9)
#   VLLM_SPEC=latest bash setup_env.sh      # newest vLLM (CUDA 13; needs NVIDIA driver >= 580)
#   WORK=/big/disk bash setup_env.sh        # somewhere else
# Afterwards, in every new shell:  source env.sh
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
WORK="${WORK:-$(cd "$HERE/.." && pwd)}"
ENV="$WORK/envs/pit"
PY="${PYTHON:-python3}"
SPEC="${VLLM_SPEC:-pinned}"

echo "== 1/6 GPU driver"
DRV_CUDA="$(nvidia-smi 2>/dev/null | grep -oE 'CUDA Version: [0-9.]+' | grep -oE '[0-9.]+$' || true)"
if [ -z "$DRV_CUDA" ]; then echo "   nvidia-smi not found: no GPU visible in this session"; exit 1; fi
echo "   driver supports CUDA $DRV_CUDA; install: $SPEC"
need="12.9"; [ "$SPEC" = "latest" ] && need="13.0"
if ! "$PY" -c "import sys; sys.exit(0 if tuple(map(int,'$DRV_CUDA'.split('.')[:2])) >= tuple(map(int,'$need'.split('.'))) else 1)"; then
  echo "   this install needs a driver supporting CUDA >= $need (you have $DRV_CUDA)."
  [ "$SPEC" = "latest" ] && echo "   use the pinned stack instead: bash setup_env.sh"
  exit 1
fi

mkdir -p "$WORK/envs" "$WORK/.cache/pip" "$WORK/.cache/huggingface" "$WORK/.cache/vllm" \
         "$WORK/.cache/triton" "$WORK/.cache/inductor"
echo "== 2/6 folders and env.sh  (WORK=$WORK, free: $(df -h "$WORK" | awk 'NR==2{print $4}'))"
cat > "$HERE/env.sh" <<ENVEOF
# generated by setup_env.sh -- source this in every new shell
export PIP_CACHE_DIR="$WORK/.cache/pip"
export HF_HOME="$WORK/.cache/huggingface"
export VLLM_CACHE_ROOT="$WORK/.cache/vllm"
export TRITON_CACHE_DIR="$WORK/.cache/triton"
export TORCHINDUCTOR_CACHE_DIR="$WORK/.cache/inductor"
export PYTHONNOUSERSITE=1
if [ -f "$ENV/bin/activate" ]; then source "$ENV/bin/activate"; fi
ENVEOF
source "$HERE/env.sh"

echo "== 3/6 virtualenv $ENV"
if [ ! -f "$ENV/bin/activate" ]; then "$PY" -m venv "$ENV"; fi
source "$ENV/bin/activate"
echo "   python: $(command -v python)  ($(python --version))"
python -m pip install -q -U pip

echo "== 4/6 packages ($SPEC)"
if [ "$SPEC" = "latest" ]; then
  python -m pip install -U vllm accelerate pandas scikit-learn requests "yfinance>=0.2.54"
else
  python -m pip install -r "$HERE/requirements.txt"
  echo "   torchcodec: CPU build (the default CUDA 13 build fails on a CUDA 12 driver)"
  python -m pip install --no-deps --force-reinstall "torchcodec==0.16.*" --index-url https://download.pytorch.org/whl/cpu
fi

echo "== 5/6 check"
python "$HERE/check_env.py"

echo "== 6/6 done"
cat <<MSG

In every new shell:   cd $HERE && source env.sh
Whole pipeline:       bash run_pipeline.sh
One method by hand:   python methods/1_rule_based.py --models phi-4-mini --limit 20
If a model needs a Hugging Face login: hf auth login   (token is stored under \$HF_HOME)
MSG
